import Anthropic from "@anthropic-ai/sdk";

export type MeetingNotesInput = {
  title: string;
  transcript: string;
  participants?: string[];
  durationSec?: number;
  occurredAt?: string; // ISO
};

function formatDuration(totalSec?: number) {
  if (!totalSec || totalSec <= 0) return "unknown";
  const m = Math.floor(totalSec / 60);
  const s = totalSec % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}

function header(input: MeetingNotesInput) {
  const when = input.occurredAt ? new Date(input.occurredAt).toLocaleString() : new Date().toLocaleString();
  const who = input.participants?.length ? input.participants.join(", ") : "—";
  return [
    `# ${input.title}`,
    "",
    `- **When:** ${when}`,
    `- **Duration:** ${formatDuration(input.durationSec)}`,
    `- **Participants:** ${who}`,
    "",
  ].join("\n");
}

// ─── AI summary via Claude (used when ANTHROPIC_API_KEY is configured) ──────────
async function summarizeWithClaude(input: MeetingNotesInput): Promise<string> {
  const client = new Anthropic(); // reads ANTHROPIC_API_KEY from the environment

  const system =
    "You are a meeting-notes assistant. You are given a rough, possibly noisy speech-to-text " +
    "transcript of a call. Produce clear, well-structured meeting notes in GitHub-flavored " +
    "Markdown. Use these sections, omitting any that have no content: " +
    "'## Summary' (2-4 sentences), '## Key points' (bullets), '## Decisions' (bullets), and " +
    "'## Action items' (bullets, prefix each with the owner if identifiable, e.g. '- Alice: ...'). " +
    "Do not invent facts that are not supported by the transcript. Be concise. Output only the Markdown body " +
    "(no title — it is added separately).";

  const userText =
    `Meeting title: ${input.title}\n` +
    `Participants: ${input.participants?.join(", ") || "unknown"}\n` +
    `Duration: ${formatDuration(input.durationSec)}\n\n` +
    `Transcript:\n"""\n${input.transcript.slice(0, 200_000)}\n"""`;

  const response = await client.messages.create({
    model: "claude-opus-4-8",
    max_tokens: 4096,
    thinking: { type: "adaptive" },
    system,
    messages: [{ role: "user", content: userText }],
  });

  const body = response.content
    .filter((block): block is Anthropic.TextBlock => block.type === "text")
    .map((block) => block.text)
    .join("\n")
    .trim();

  return `${header(input)}${body}\n\n---\n\n<details><summary>Full transcript</summary>\n\n${input.transcript}\n\n</details>\n`;
}

// ─── Heuristic fallback (no API key required) ───────────────────────────────────
const ACTION_HINTS = /\b(action item|todo|to-do|follow up|follow-up|i will|we will|we'll|i'll|let's|assign|next step|by (monday|tuesday|wednesday|thursday|friday|tomorrow|eod|end of))\b/i;
const DECISION_HINTS = /\b(decide|decided|agree|agreed|we should|conclusion|final|go with|approved)\b/i;

function splitSentences(text: string): string[] {
  return text
    .replace(/\s+/g, " ")
    .split(/(?<=[.!?])\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

function summarizeHeuristically(input: MeetingNotesInput): string {
  const sentences = splitSentences(input.transcript);
  const actionItems = sentences.filter((s) => ACTION_HINTS.test(s));
  const decisions = sentences.filter((s) => DECISION_HINTS.test(s) && !ACTION_HINTS.test(s));

  // Naive summary: first sentence + a middle sentence + last sentence.
  const summaryParts: string[] = [];
  if (sentences.length) summaryParts.push(sentences[0]);
  if (sentences.length > 2) summaryParts.push(sentences[Math.floor(sentences.length / 2)]);
  if (sentences.length > 1) summaryParts.push(sentences[sentences.length - 1]);

  const keyPoints = sentences
    .filter((s) => s.length > 40 && !actionItems.includes(s) && !decisions.includes(s))
    .slice(0, 6);

  const sections: string[] = [header(input)];

  sections.push("> _AI summarization is not configured (no `ANTHROPIC_API_KEY`); these notes were generated by a built-in summarizer._\n");

  if (summaryParts.length) {
    sections.push("## Summary\n\n" + summaryParts.join(" ") + "\n");
  }
  if (keyPoints.length) {
    sections.push("## Key points\n\n" + keyPoints.map((p) => `- ${p}`).join("\n") + "\n");
  }
  if (decisions.length) {
    sections.push("## Decisions\n\n" + decisions.map((d) => `- ${d}`).join("\n") + "\n");
  }
  if (actionItems.length) {
    sections.push("## Action items\n\n" + actionItems.map((a) => `- ${a}`).join("\n") + "\n");
  }

  sections.push(`---\n\n<details><summary>Full transcript</summary>\n\n${input.transcript}\n\n</details>\n`);
  return sections.join("\n");
}

// Pull the "## Action items" bullets out of generated Markdown (works for both
// the Claude and heuristic paths, since both emit that section).
export function extractActionItems(markdown: string): string[] {
  const lines = markdown.split(/\r?\n/);
  const items: string[] = [];
  let inSection = false;
  for (const line of lines) {
    if (/^##\s+action items/i.test(line.trim())) {
      inSection = true;
      continue;
    }
    if (inSection && /^##\s+/.test(line.trim())) break; // next heading ends the section
    if (inSection) {
      const m = line.match(/^\s*[-*]\s+(.*\S)\s*$/);
      if (m) {
        // Strip a leading speech timestamp like "[10:03] " if present.
        items.push(m[1].replace(/^\[\d{1,2}:\d{2}\]\s*/, "").trim());
      }
    }
  }
  return items.slice(0, 25);
}

export type MeetingNotesResult = { markdown: string; actionItems: string[] };

export async function generateMeetingNotes(input: MeetingNotesInput): Promise<MeetingNotesResult> {
  const trimmed = { ...input, transcript: input.transcript.trim() };
  if (!trimmed.transcript) {
    return { markdown: `${header(trimmed)}_No speech was captured during this call._\n`, actionItems: [] };
  }

  let markdown: string;
  if (process.env.ANTHROPIC_API_KEY) {
    try {
      markdown = await summarizeWithClaude(trimmed);
    } catch (error) {
      console.warn("[meeting-notes] Claude summarization failed, falling back to heuristic:", error instanceof Error ? error.message : error);
      markdown = summarizeHeuristically(trimmed);
    }
  } else {
    markdown = summarizeHeuristically(trimmed);
  }

  return { markdown, actionItems: extractActionItems(markdown) };
}
